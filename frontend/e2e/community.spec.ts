import { expect, test, type Page } from '@playwright/test'

async function login(page: Page, role: 'admin' | 'clover' | 'demo') {
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill(`${role}@calisapp.com`)
  await page.getByLabel('Contraseña', { exact: true }).fill(role === 'admin' ? 'Admin123!' : role === 'clover' ? 'Clover1234!' : 'Demo1234!')
  await page.getByRole('button', { name: 'Log In', exact: true }).click()
  await expect(page).not.toHaveURL(/\/login$/)
  await expect(page.getByRole('navigation', { name: 'Navegación principal' })).toBeVisible()
}

async function logout(page: Page) {
  await page.goto('/profile')
  await page.getByRole('button', { name: 'Cerrar sesión' }).click()
  await expect(page).toHaveURL(/\/login$/)
}

